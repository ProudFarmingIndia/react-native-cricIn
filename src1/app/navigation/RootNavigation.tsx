/*
|--------------------------------------------------------------------------
| RootNavigation.js
|--------------------------------------------------------------------------
|
| MASTER APP NAVIGATION
|
| PURPOSE:
| Decide which flow should open:
|
| 1. Splash Screen
| 2. Auth Flow
| 3. Main App Flow
|
|--------------------------------------------------------------------------
*/

import React, {
  useEffect,
  useState,
} from 'react';

/*
|--------------------------------------------------------------------------
| AUTH PROVIDER
|--------------------------------------------------------------------------
|
| Access global login state
|
|--------------------------------------------------------------------------
*/

import { useAuth } from '../providers/AuthProvider';

/*
|--------------------------------------------------------------------------
| NAVIGATION FLOWS
|--------------------------------------------------------------------------
*/

import AuthStack from './AuthStack';

import MainStack from './MainStack';

/*
|--------------------------------------------------------------------------
| SPLASH SCREEN
|--------------------------------------------------------------------------
*/

import SplashScreen from '../../features/splash/screens/SplashScreen';

/*
|--------------------------------------------------------------------------
| ROOT NAVIGATION COMPONENT
|--------------------------------------------------------------------------
*/

export default function RootNavigation() {
  /*
  |--------------------------------------------------------------------------
  | GET LOGIN STATE
  |--------------------------------------------------------------------------
  */

  const { isLoggedIn } = useAuth();

  /*
  |--------------------------------------------------------------------------
  | SPLASH STATE
  |--------------------------------------------------------------------------
  */

  const [isSplashVisible, setIsSplashVisible] =
    useState(true);

  /*
  |--------------------------------------------------------------------------
  | SHOW SPLASH FOR 2.5 SEC
  |--------------------------------------------------------------------------
  */

  useEffect(() => {
    const timer = setTimeout(() => {
      setIsSplashVisible(false);
    }, 2500);

    return () => clearTimeout(timer);
  }, []);

  /*
  |--------------------------------------------------------------------------
  | SHOW SPLASH SCREEN
  |--------------------------------------------------------------------------
  */

  if (isSplashVisible) {
    return <SplashScreen />;
  }

  /*
  |--------------------------------------------------------------------------
  | AUTH FLOW
  |--------------------------------------------------------------------------
  |
  | If user NOT logged in
  |
  */

  if (!isLoggedIn) {
    return <AuthStack />;
  }

  /*
  |--------------------------------------------------------------------------
  | MAIN APP FLOW
  |--------------------------------------------------------------------------
  |
  | If user logged in
  |
  */

  return <MainStack />;
}